"""R96 genuine Qt offscreen screenshot of offline Windows services viewer.

Generated by Windows CI, with no WinRM connection and no synthetic service data.
Not evidence of a real Windows Server or human-operated Windows desktop.
Author: Abdelhalim Talbi.
"""
import os
from pathlib import Path

os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
from PySide6.QtWidgets import QApplication
from winrm_inventory_qt import WinRMServicesPanel
from qt_font_render_gate import configure_readable_offscreen_font

app = QApplication.instance() or QApplication([])
family = configure_readable_offscreen_font(app)
panel = WinRMServicesPanel()
panel.resize(980, 610)
panel.show()
app.processEvents()
assert not panel.consent.isChecked()
assert panel.table.topLevelItemCount() == 0
assert 'Hors ligne' in panel.status.text()
assert panel.service_filter.isVisible()
destination = Path('Binary/Qualification/qt-winrm-services-r96-offline.png')
destination.parent.mkdir(parents=True, exist_ok=True)
if not panel.grab().save(str(destination), 'PNG'):
    raise SystemExit('R96_QT_CAPTURE_FAILED')
if not destination.read_bytes().startswith(b'\\x89PNG\\r\\n\\x1a\\n'):
    raise SystemExit('R96_QT_CAPTURE_INVALID')
panel.close()
print('R96_QT_OFFLINE_CAPTURE_PASS', destination.as_posix(),
      destination.stat().st_size, 'font=' + family)
